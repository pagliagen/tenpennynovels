// Methods
LocationSchema.methods.canCharacterAccess = function(characterId: Schema.Types.ObjectId, requiredPermission = 'view') {
  // Public locations are always accessible (if visible)
  if (!this.settings.private) {
    return this.settings.visible;
  }
  
  // Check if character is owner
  if (this.access?.ownerType === 'character' && this.access?.ownerId?.equals(characterId)) {
    return true;
  }
  
  // Check character-specific access
  if (this.access?.characterAccess) {
    const access = this.access.characterAccess.find((a: any) => a.characterId.equals(characterId));
    if (access) {
      // Check if access is expired
      if (access.duration === 'temporary' && access.expiresAt && new Date() > access.expiresAt) {
        return false;
      }
      return access.permissions.includes(requiredPermission);
    }
  }
  
  return false;
};

LocationSchema.methods.canCorporationAccess = function(corporationId: Schema.Types.ObjectId, memberRole?: string) {
  if (!this.settings.private) {
    return this.settings.visible;
  }
  
  // Check if corporation owns the location
  if (this.access?.ownerType === 'corporation' && this.access?.ownerId?.equals(corporationId)) {
    return true;
  }
  
  // Check corporation access rules
  if (this.access?.corporationAccess) {
    const access = this.access.corporationAccess.find((a: any) => a.corporationId.equals(corporationId));
    if (access) {
      // Check minimum role requirement
      if (access.minimumRole && memberRole) {
        // Role hierarchy check would go here
        return true; // Simplified for now
      }
      return true;
    }
  }
  
  return false;
};

LocationSchema.methods.grantCharacterAccess = function(characterId: Schema.Types.ObjectId, permissions: string[], grantedBy: Schema.Types.ObjectId, duration = 'permanent', expiresAt?: Date) {
  if (!this.access) {
    this.access = { characterAccess: [], corporationAccess: [] };
  }
  
  // Remove existing access for this character
  this.access.characterAccess = this.access.characterAccess.filter((a: any) => !a.characterId.equals(characterId));
  
  // Add new access
  this.access.characterAccess.push({
    characterId,
    permissions,
    grantedBy,
    grantedAt: new Date(),
    duration,
    expiresAt
  });
};

LocationSchema.methods.revokeCharacterAccess = function(characterId: Schema.Types.ObjectId) {
  if (this.access?.characterAccess) {
    this.access.characterAccess = this.access.characterAccess.filter((a: any) => !a.characterId.equals(characterId));
  }
};

LocationSchema.methods.updateStatistics = function(updateData: Partial<ILocation['statistics']>) {
  Object.assign(this.statistics, updateData);
  this.statistics.lastActivityAt = new Date();
};

LocationSchema.methods.addNPC = function(npcId: Schema.Types.ObjectId, priority = 1, relevance = 0.5) {
  // Remove existing NPC entry
  this.npcs = this.npcs.filter((n: any) => !n.npcId.equals(npcId));
  
  // Add new entry
  this.npcs.push({
    npcId,
    isActive: true,
    activationPriority: priority,
    contextualRelevance: relevance
  });
};

LocationSchema.methods.getActiveNPCs = function() {
  return this.npcs.filter((n: any) => n.isActive).sort((a: any, b: any) => b.activationPriority - a.activationPriority);
};

// Occupant management methods
LocationSchema.methods.addOccupant = async function(characterId: Schema.Types.ObjectId, characterName: string, currentTag?: string) {
  const now = new Date();

  // Use atomic update to avoid full document validation
  // First, remove any existing occupant with same characterId
  await mongoose.model<ILocation>('Location').updateOne(
    { _id: this._id },
    { $pull: { occupants: { characterId } } }
  );

  // Then add new occupant entry
  return mongoose.model<ILocation>('Location').updateOne(
    { _id: this._id },
    {
      $push: {
        occupants: {
          characterId,
          characterName,
          enteredAt: now,
          lastSeen: now,
          isActive: true,
          currentTag: currentTag || undefined
        }
      }
    }
  );
};


import mongoose, { Schema, model, Document, QueryFilter } from 'mongoose';
import { softDeletePlugin, SoftDeleteMethods } from '../plugins/softDeletePlugin';

export interface ILocationPosition {
  name: string;
  image?: string;
  description?: string;
}

export interface ILocation extends Document, SoftDeleteMethods {
  // Basic info
  name: string;
  slug: string;
  description: string;
  district: string;
  parentLocation?: Schema.Types.ObjectId;
  imageUrl?: string; // URL CDN (upload manuale via pannello gestione)
  image?: string;    // Filename statico in apps/game/public/artifacts/locations/ (es. "london.png"),
                      // generato da local-tools/imagegen — stesso pattern di Item.image
  descriptionImages: string[]; // URL immagini mostrate accanto alla descrizione nel popup info location

  // Location settings (control switches)
  settings: {
    visible: boolean;    // Location appears in navigation
    chat: boolean;       // Chat functionality available
    shop: boolean;       // Commerce/trading functionality
    private: boolean;    // Access control system activated
  };
  
  // Hierarchy and positioning
  locationLevel: 'root' | 'district' | 'location';
  sortOrder: number;
  
  // Private location access control
  access?: {
    ownerId?: Schema.Types.ObjectId;  // Character who owns this location
    ownerType?: 'character' | 'corporation';
    
    // Character-specific access grants
    characterAccess: {
      characterId: Schema.Types.ObjectId;
      permissions: ('view' | 'chat' | 'manage')[];
      grantedBy: Schema.Types.ObjectId;
      grantedAt: Date;
      duration: 'permanent' | 'temporary';
      expiresAt?: Date;
    }[];
    
    // Corporation access (members of these corporations can access)
    corporationAccess: {
      corporationId: Schema.Types.ObjectId;
      permissions: ('view' | 'chat' | 'manage')[];
      minimumRole?: string;
    }[];
  };

  // Lightweight name+avatar personas scoped to this location, used to override
  // the poster's displayed name/avatar (e.g. "il barista", "il maggiordomo").
  // Usable by the location owner and by master. Distinct from `npcs` (full
  // Character-backed PNGs) and from Character.fakePngs (per-character masking).
  locationPngs?: {
    name: string;
    surname?: string;
    avatar?: string;
    createdAt: Date;
    createdBy: Schema.Types.ObjectId;
  }[];

  // Location limits and rules
  maxOccupants?: number;
  accessRules?: {
    requiredLevel?: number;
    bannedCharacters?: Schema.Types.ObjectId[];
    allowedCorporations?: Schema.Types.ObjectId[];
    timeRestrictions?: {
      openTime?: string;
      closeTime?: string;
      allowedDays?: number[];
    };
  };
  
  // Active Gaming Session Management
  // Auto-created session when chat activity starts, expires after 3 hours of inactivity
  activeSession?: {
    sessionId: Schema.Types.ObjectId;  // Reference to GamingSession document
    startedAt: Date;                   // When the session was auto-created
    lastActivityAt: Date;              // Last message timestamp (for TTL)
    expiresAt: Date;                   // When session will auto-finalize (3 hours from last activity)
    isAutoGenerated: boolean;          // True if auto-created, false if master-created
    participantIds: Schema.Types.ObjectId[]; // Characters who participated (for quick lookup)
  };

  // Current occupants (real-time presence tracking)
  occupants: {
    characterId: Schema.Types.ObjectId;
    characterName: string;
    enteredAt: Date;
    lastSeen: Date;
    isActive: boolean; // true if character is currently online
    currentTag?: string; // Current position tag (e.g., "Tavolo", "Bancone del Bar")
  }[];

  // NPCs in this location
  npcs: {
    npcId: Schema.Types.ObjectId;
    isActive: boolean;
    activationPriority: number;
    contextualRelevance: number;
  }[];

  // Bot AI integration
  bot_enabled: boolean; // true = bot interaction enabled for this location
  botCharacterId?: Schema.Types.ObjectId; // Character ID of the bot assigned to this location

  // Bot round tracking — collects all player actions before notifying the bot
  botRound?: {
    roundNumber: number;
    actedCharacterIds: Schema.Types.ObjectId[];
    roundActionIds: Schema.Types.ObjectId[];
    startedAt: Date;
  };

  // Location statistics (updated periodically)
  statistics: {
    totalVisits: number;
    uniqueVisitors: number;
    averageStayTime: number; // in minutes
    messagesExchanged: number;
    lastActivityAt?: Date;
    peakHours: string[];
  };

  // Physical positions/sub-locations (e.g., "Tavolo 1", "Bancone", "Angolo Nord")
  // Used in chat to indicate where character is within the location
  positions?: ILocationPosition[];

  // Management info
  createdBy: Schema.Types.ObjectId;
  lastModifiedBy?: Schema.Types.ObjectId;
  
  // Timestamps
  createdAt: Date;
  updatedAt: Date;
}


// Session management methods
LocationSchema.methods.getOrCreateSession = async function(characterId: Schema.Types.ObjectId, characterName: string) {
  const now = new Date();
  const SESSION_TTL_HOURS = 3;

  // Check if there's an active session that hasn't expired
  if (this.activeSession && this.activeSession.expiresAt > now) {
    // Refresh the TTL
    this.activeSession.lastActivityAt = now;
    this.activeSession.expiresAt = new Date(now.getTime() + SESSION_TTL_HOURS * 60 * 60 * 1000);

    // Add character to participants if not already there
    if (!this.activeSession.participantIds.some((id: any) => id.equals(characterId))) {
      this.activeSession.participantIds.push(characterId);

      // Also update GamingSession participants
      const GamingSession = mongoose.model('GamingSession');
      await GamingSession.findByIdAndUpdate(this.activeSession.sessionId, {
        $addToSet: {
          participants: {
            characterId,
            characterName,
            joinedAt: now,
            wasActive: true,
            participationScore: 5
          }
        }
      });
    }

    return this.activeSession.sessionId;
  }

  // Create new auto-generated gaming session
  const GamingSession = mongoose.model('GamingSession');
  const newSession = await GamingSession.create({
    title: `Auto-Session at ${this.name}`,
    description: `Automatically generated session from chat activity`,
    masterId: characterId, // First participant becomes temporary master
    masterName: characterName,
    sessionDate: now,
    startTime: now,
    estimatedDuration: 180, // 3 hours default
    primaryLocation: this._id,
    sessionType: 'social',
    difficultyLevel: 'medium',
    participants: [{
      characterId,
      characterName,
      joinedAt: now,
      wasActive: true,
      participationScore: 5
    }],
    status: 'active',
    experienceAssigned: false
  });

  this.activeSession = {
    sessionId: newSession._id,
    startedAt: now,
    lastActivityAt: now,
    expiresAt: new Date(now.getTime() + SESSION_TTL_HOURS * 60 * 60 * 1000),
    isAutoGenerated: true,
    participantIds: [characterId]
  };

  return newSession._id;
};

LocationSchema.methods.refreshSessionTTL = async function(characterId?: Schema.Types.ObjectId, characterName?: string) {
  const now = new Date();
  const SESSION_TTL_HOURS = 3;

  if (this.activeSession) {
    this.activeSession.lastActivityAt = now;
    this.activeSession.expiresAt = new Date(now.getTime() + SESSION_TTL_HOURS * 60 * 60 * 1000);

    // Add character to participants if provided and not already there
    if (characterId && !this.activeSession.participantIds.some((id: any) => id.equals(characterId))) {
      this.activeSession.participantIds.push(characterId);

      // Also update GamingSession participants
      if (characterName) {
        const GamingSession = mongoose.model('GamingSession');
        await GamingSession.findByIdAndUpdate(this.activeSession.sessionId, {
          $addToSet: {
            participants: {
              characterId,
              characterName,
              joinedAt: now,
              wasActive: true,
              participationScore: 5
            }
          }
        });
      }
    }
  }
};

LocationSchema.methods.finalizeAutoSession = async function() {
  if (!this.activeSession || !this.activeSession.isAutoGenerated) {
    return;
  }

  const now = new Date();
  const GamingSession = mongoose.model('GamingSession');

  // Update session with final data
  await GamingSession.findByIdAndUpdate(this.activeSession.sessionId, {
    endTime: now,
    status: 'completed',
    totalActiveTime: Math.round((now.getTime() - this.activeSession.startedAt.getTime()) / 60000) // minutes
  });

  // Clear active session from location
  this.activeSession = undefined;
  return this.save();
};

LocationSchema.methods.isSessionActive = function() {
  if (!this.activeSession) return false;
  return this.activeSession.expiresAt > new Date();
};

// Static methods
LocationSchema.statics.findAccessibleByCharacter = function(characterId: Schema.Types.ObjectId, corporationIds: Schema.Types.ObjectId[] = []) {
  const query: QueryFilter<ILocation> = {
    $or: [
      // Public locations
      { 'settings.visible': true, 'settings.private': false },
      // Character owns the location
      { 'access.ownerType': 'character', 'access.ownerId': characterId },
      // Character has specific access
      { 'access.characterAccess.characterId': characterId },
      // Character's corporations have access
      ...(corporationIds.length > 0 ? [
        { 'access.ownerType': 'corporation' as const, 'access.ownerId': { $in: corporationIds } },
        { 'access.corporationAccess.corporationId': { $in: corporationIds } }
      ] : [])
    ]
  };
  return this.find(query);
};

